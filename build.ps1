#requires -Version 7
<#
  Wires every harness to ~/agent-core.

  Claude Code and omp resolve `@~/path` imports natively (verified), so they get
  a thin stub that imports core/ directly - no generated copy to drift.

  Hermes has no import syntax and reads SOUL.md only from HERMES_HOME, so it is the
  one generated copy: the same stub with every `@~/` line inlined. verify.ps1 fails
  when that copy drifts from a fresh build.
#>
[CmdletBinding()]
param(
  [switch]$WhatIf,
  [ValidateSet('claude', 'omp', 'hermes')]
  [string[]]$Only
)

$ErrorActionPreference = 'Stop'
$Root = $PSScriptRoot
$Home_ = $HOME
$manifest = Import-PowerShellDataFile (Join-Path $Root 'manifest.psd1')
$targets = if ($Only) { $Only } else { $manifest.Keys }

function Write-Target {
  param([string]$Path, [string]$Content)
  # CRLF per core/00-identity.md. Normalise before comparing, or -WhatIf reports a
  # change on every run purely from line endings.
  $Content = ($Content -replace "`r`n", "`n") -replace "`n", "`r`n"
  if ($WhatIf) {
    $old = if (Test-Path $Path) { Get-Content -Raw -LiteralPath $Path } else { '' }
    if ($old -eq $Content) { Write-Host "  = $Path (unchanged)" -ForegroundColor DarkGray }
    else { Write-Host "  ~ $Path (would change: $($old.Length) -> $($Content.Length) bytes)" -ForegroundColor Yellow }
    return
  }
  $dir = Split-Path -Parent $Path
  if (-not (Test-Path $dir)) { New-Item -ItemType Directory -Force -Path $dir | Out-Null }
  [System.IO.File]::WriteAllText($Path, $Content, [System.Text.UTF8Encoding]::new($false))
  Write-Host "  + $Path" -ForegroundColor Green
}

function Get-Stub {
  param([string]$Harness)
  $lines = @(
    "<!-- Generated by ~/agent-core/build.ps1. Edit agent-core, not this file. -->"
    ""
    "@~/agent-core/adapters/$Harness.md"
    ""
  )
  foreach ($f in $manifest[$Harness]) {
    if ($f -eq '70-shared-memory' -and -not (Test-Path -LiteralPath (Join-Path $Home_ 'Axiom/integrations/instructions.md') -PathType Leaf)) {
      Write-Host "  skipping optional Axiom instructions (~/Axiom/integrations/instructions.md not found)" -ForegroundColor DarkGray
      continue
    }
    $lines += "@~/agent-core/core/$f.md"; $lines += ""
  }
  ($lines -join "`n")
}

function Get-HermesSoulPath {
  $hermesHome = if ($env:HERMES_HOME) { $env:HERMES_HOME } else { Join-Path $env:LOCALAPPDATA 'hermes' }
  Join-Path $hermesHome 'SOUL.md'
}

# Inline `@~/path` lines recursively (70-shared-memory is itself an import).
function Expand-Imports {
  param([string]$Text, [int]$Depth = 0)
  if ($Depth -gt 5) { throw 'Import nesting deeper than 5 - is there a cycle?' }
  $out = foreach ($line in ($Text -split "`r?`n")) {
    if ($line -match '^@~/(\S+)$') {
      $path = Join-Path $Home_ $Matches[1]
      if (-not (Test-Path -LiteralPath $path -PathType Leaf)) { throw "Import not found: $line" }
      (Expand-Imports (Get-Content -Raw -LiteralPath $path) ($Depth + 1)).TrimEnd()
    }
    else { $line }
  }
  ($out -join "`n")
}

Write-Host "agent-core build" -ForegroundColor Cyan

if ('claude' -in $targets) {
  Write-Host "claude  -> import stub"
  Write-Target (Join-Path $Home_ '.claude/CLAUDE.md') (Get-Stub 'claude')
}

if ('omp' -in $targets) {
  Write-Host "omp     -> import stub"
  Write-Target (Join-Path $Home_ '.omp/agent/AGENTS.md') (Get-Stub 'omp')
}

if ('hermes' -in $targets) {
  Write-Host "hermes  -> inlined SOUL.md"
  Write-Target (Get-HermesSoulPath) (Expand-Imports (Get-Stub 'hermes'))
}



Write-Host "done. run verify.ps1 to confirm each harness loads it." -ForegroundColor Cyan
